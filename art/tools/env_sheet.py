"""Build art/previews/env_contact.png - the whole environment kit, both palettes.

    python art/tools/env_sheet.py

One cell per piece: the warm palette (Game A, the plaza) on the left and the cool one
(Game B, the waterfront) on the right, from the same geometry. That pairing is the point of
the sheet - it is how a cold reader sees that the second map is a different place and not a
re-skin, and that the difference is carried by materials, so there is one FBX per piece.

The per-piece PNGs are regenerated by `build_env.py` and are not committed; this sheet is.
Needs Pillow in the system Python, like the other art sheets.
"""

from __future__ import annotations

import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.abspath(os.path.join(HERE, ".."))
EXPORT = os.path.join(ART, "export_env")
OUT = os.path.join(ART, "previews", "env_contact.png")

SHOT_W = 300
COLUMNS = 3
PAD = 16
GAP = 10
CAPTION_H = 52
HEADER_H = 86
BG = (24, 26, 30)
CELL = (34, 37, 42)
FG = (234, 238, 242)
SUB = (152, 160, 170)
WARN = (226, 150, 90)


def font(size, bold=False):
    names = ("segoeuib.ttf", "arialbd.ttf") if bold else ("segoeui.ttf", "arial.ttf",
                                                          "DejaVuSans.ttf")
    for name in names:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def main():
    rows = []
    if not os.path.isdir(EXPORT):
        print("no art/export_env - run the environment build first")
        return 1
    for name in sorted(os.listdir(EXPORT)):
        p = os.path.join(EXPORT, name, "manifest.json")
        if os.path.exists(p):
            with open(p, "r", encoding="utf-8") as fh:
                rows.append(json.load(fh))
    if not rows:
        print("no environment manifests under art/export_env")
        return 1
    # buildings first, then the ground they stand on, then the furniture
    order = {"building": 0, "ground": 1, "street": 2, "planting": 3, "water": 4}
    rows.sort(key=lambda m: (order.get(m.get("category"), 9), m["id"]))

    first = None
    for m in rows:
        rel = (m.get("previews") or {}).get("warm")
        if rel and os.path.exists(os.path.join(ART, rel)):
            first = Image.open(os.path.join(ART, rel))
            break
    if first is None:
        print("no preview PNGs on disk - run build_env.py without --no-render")
        return 1
    shot_h = int(SHOT_W * first.height / first.width)

    cell_w = SHOT_W * 2 + 4
    cols = min(COLUMNS, len(rows))
    lines = (len(rows) + cols - 1) // cols
    width = PAD * 2 + cols * cell_w + (cols - 1) * GAP
    height = HEADER_H + PAD * 2 + lines * (shot_h + CAPTION_H) + (lines - 1) * GAP
    sheet = Image.new("RGB", (width, height), BG)
    draw = ImageDraw.Draw(sheet)

    f_title = font(26, bold=True)
    f_head = font(15)
    f_cap = font(16, bold=True)
    f_sub = font(13)

    total = sum(m.get("triangles", 0) for m in rows)
    draw.text((PAD, 16), "DynamicContents - environment kit", font=f_title, fill=FG)
    draw.text((PAD, 50),
              "%d pieces  ·  %s triangles in the whole kit  ·  left: warm (Game A, the plaza)  "
              "·  right: cool (Game B, the waterfront)  ·  one FBX per piece, the palette is "
              "material instances" % (len(rows), format(total, ",")),
              font=f_head, fill=SUB)
    draw.text((PAD, 68),
              "No text, no signs, no logos anywhere in the kit; nothing here can wear a brand.",
              font=f_sub, fill=SUB)

    for index, m in enumerate(rows):
        col, line = index % cols, index // cols
        x = PAD + col * (cell_w + GAP)
        y = HEADER_H + PAD + line * (shot_h + CAPTION_H + GAP)
        draw.rectangle([x, y, x + cell_w, y + shot_h + CAPTION_H], fill=CELL)

        for half, palette in ((0, "warm"), (1, "cool")):
            rel = (m.get("previews") or {}).get(palette)
            if rel and os.path.exists(os.path.join(ART, rel)):
                shot = Image.open(os.path.join(ART, rel)).convert("RGB")
                shot = shot.resize((SHOT_W, shot_h), Image.LANCZOS)
                sheet.paste(shot, (x + half * (SHOT_W + 4), y))

        s = m["bounds"]["size"]
        draw.text((x + 10, y + shot_h + 7),
                  "%s   %s" % (m["id"], m.get("category", "")), font=f_cap, fill=FG)
        over = m.get("triangles", 0) > m.get("triangle_budget", 1 << 30)
        draw.text((x + 10, y + shot_h + 28),
                  "%.2f x %.2f x %.2f m   ·   %s tris of %s   ·   %s   ·   %s"
                  % (s[0], s[1], s[2], format(m.get("triangles", 0), ","),
                     format(m.get("triangle_budget", 0), ","), m.get("collision", "?"),
                     " ".join(m.get("material_slots", []))),
                  font=f_sub, fill=WARN if over else SUB)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    sheet.save(OUT)
    print("wrote %s  (%d x %d, %d pieces)" % (OUT, width, height, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
